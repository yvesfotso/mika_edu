const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, fr };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const singular = `${key}_one` as MessageKey;
  const useSingular = (vars?.n === 1 || (vars?.n === 0 && locale === "fr")) && singular in en;
  let text = MESSAGES[locale][useSingular ? singular : key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
